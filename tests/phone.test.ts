import { describe, expect, it } from "vitest";
import { normalisePhone } from "@/lib/phone";

describe("normalisePhone", () => {
  it.each([
    ["082 123 4567", "+27821234567"],
    ["0821234567", "+27821234567"],
    ["082-123-4567", "+27821234567"],
    ["27821234567", "+27821234567"],
    ["+27821234567", "+27821234567"],
    ["+27 82 123 4567", "+27821234567"],
    ["0027821234567", "+27821234567"],
    ["+27 (0) 82 123 4567", "+27821234567"],
    ["(082) 123.4567", "+27821234567"],
    ["821234567", "+27821234567"],
    [" 011 123 4567 ", "+27111234567"],
    [821234567, "+27821234567"],
  ])("normalises %s", (input, expected) => {
    expect(normalisePhone(input)).toBe(expected);
  });

  it.each([
    "", "   ", "abc", "082 123", "12345", "+1 415 555 2671", "+44 7911 123456", "0921234567890",
    "0000000000", "082 123 456 789", null, undefined, "call me",
  ])("rejects %s", (input) => {
    expect(normalisePhone(input as string)).toBeNull();
  });
});
